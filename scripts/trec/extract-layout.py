# Regenerates lib/pdf/trec/rei76-layout.ts from TREC's official fillable PDF.
#
#   curl -o /tmp/rei76.pdf "https://www.trec.texas.gov/sites/default/files/pdf-forms/REI%207-6_fillable.pdf"
#   pip install pymupdf
#   python3 -I scripts/trec/extract-layout.py /tmp/rei76.pdf > lib/pdf/trec/rei76-layout.ts
#
# Every word's starting x / baseline and every filled rule/border is copied
# from the promulgated form, so pages 1-2 and the page header/footer render at
# TREC's own coordinates (22 TAC 535.223: identical spacing, borders, text
# placement). Only run this again for a new TREC form revision.
import json
import sys

import fitz

doc = fitz.open(sys.argv[1])


def font_code(name):
    if "Calibri-Bold" in name:
        return "HB"  # no Calibri in the PDF base fonts; Helvetica-Bold stands in
    if "Bold" in name:
        return "B"
    if "Italic" in name:
        return "I"
    return "R"


def words(page, y0=-1, y1=9999):
    out = []
    for b in page.get_text("rawdict")["blocks"]:
        for l in b.get("lines", []):
            for s in l["spans"]:
                base = s["origin"][1]
                if not (y0 <= base <= y1):
                    continue
                f = font_code(s["font"])
                color = "#%06x" % s["color"]
                word, wx = "", None
                for ch in s["chars"] + [None]:
                    if ch is None or ch["c"].isspace():
                        if word:
                            if word in ("", ""):
                                word = "•"
                            out.append([round(wx, 2), round(base, 2), f, round(s["size"], 1), word] + ([color] if color != "#000000" else []))
                        word, wx = "", None
                    else:
                        if wx is None:
                            wx = ch["origin"][0]
                        word += ch["c"]
    return out


def rects(page, y0=-1, y1=9999, skip=lambda r: False):
    out = []
    for d in page.get_drawings():
        if d.get("fill") is None:
            continue
        color = "#%02x%02x%02x" % tuple(round(c * 255) for c in d["fill"][:3])
        # Most rules are "re" items; a few are quads/lines, so use their bounds.
        its = d["items"]
        if all(it[0] == "re" for it in its):
            boxes = [it[1] for it in its]
        elif its[0][0] == "re" and all(it[0] == "l" for it in its[1:]):
            # Outlined frame: outer rect with an inner polygon cut out.
            o = its[0][1]
            pts = [pt for it in its[1:] for pt in it[1:]]
            i = fitz.Rect(min(q.x for q in pts), min(q.y for q in pts), max(q.x for q in pts), max(q.y for q in pts))
            boxes = [
                fitz.Rect(o.x0, o.y0, o.x1, i.y0),
                fitz.Rect(o.x0, i.y1, o.x1, o.y1),
                fitz.Rect(o.x0, i.y0, i.x0, i.y1),
                fitz.Rect(i.x1, i.y0, o.x1, i.y1),
            ]
        else:
            boxes = [d["rect"]]
        for r in boxes:
            if r.y0 < y0 or r.y1 > y1 or skip(r):
                continue
            out.append([round(r.x0, 2), round(r.y0, 2), round(r.width, 2), round(r.height, 2), color])
    return out


p1, p2, p3 = doc[0], doc[1], doc[2]
data = {
    "page1": {"words": words(p1), "rects": rects(p1)},
    "page2": {"words": words(p2), "rects": rects(p2)},
    # Repeating header/footer of the item pages (3-6), from page 3.
    "bodyHeader": {"words": words(p3, -1, 95), "rects": rects(p3, -1, 95)},
    "bodyFooter": {"words": words(p3, 740, 9999), "rects": rects(p3, 740, 9999)},
    # One checkbox (item A on page 3), relative to its top-left corner.
    "checkbox": None,
    "fields": {w.field_name: [round(v, 2) for v in w.rect] for p in (p1, p2) for w in p.widgets()},
}
cb = [r for r in rects(p3, 128, 140) if r[0] < 45]
x0 = min(r[0] for r in cb)
y0 = min(r[1] for r in cb)
data["checkbox"] = [[round(r[0] - x0, 2), round(r[1] - y0, 2), r[2], r[3], r[4]] for r in cb]

print("// GENERATED by scripts/trec/extract-layout.py from TREC's REI 7-6 (8/9/21)")
print("// fillable PDF. Do not edit by hand.")
print("// word: [x, baseline, font (R|B|I|HB), size, text, color?]; rect: [x, y, w, h, fill]")
print("export type LayoutWord = [number, number, string, number, string, string?];")
print("export type LayoutRect = [number, number, number, number, string];")
print("export interface LayoutBlock { words: LayoutWord[]; rects: LayoutRect[] }")
for k in ("page1", "page2", "bodyHeader", "bodyFooter"):
    print(f"export const {k}: LayoutBlock = {json.dumps(data[k], ensure_ascii=False)};")
print(f"export const checkbox: LayoutRect[] = {json.dumps(data['checkbox'])};")
print(f"export const fields: Record<string, [number, number, number, number]> = {json.dumps(data['fields'])};")
